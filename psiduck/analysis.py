"""Scoring, paired McNemar tests, SUMMARY.md and the README results block."""

from __future__ import annotations

import json
from math import comb
from pathlib import Path
from typing import Optional

CONFIG_ORDER = ("baseline", "latent", "latent-early-exit")
README_START = "<!-- RESULTS:START (generated by analyze.py from SUMMARY.md; do not edit) -->"
README_END = "<!-- RESULTS:END -->"


def read_jsonl(path: Path) -> dict[int, dict]:
    """idx -> record. Later lines win; a torn final line (crash mid-write) is ignored."""
    out: dict[int, dict] = {}
    if not path.exists():
        return out
    with path.open(encoding="utf-8") as f:
        for line in f:
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            out[int(r["idx"])] = r
    return out


def mcnemar_exact(b: int, c: int) -> float:
    """Exact two-sided McNemar p-value from the discordant counts b and c."""
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    p = 2 * sum(comb(n, i) for i in range(k + 1)) / 2**n
    return min(1.0, p)


def config_stats(recs: list[dict]) -> dict:
    n = len(recs)
    if n == 0:
        return dict(n=0)

    def mean(key):
        return sum(r.get(key, 0) or 0 for r in recs) / n

    return dict(
        n=n,
        correct=sum(bool(r.get("correct")) for r in recs),
        gen_tokens=mean("generated_tokens"),
        forward_passes=mean("forward_passes"),
        latent_steps=mean("latent_steps"),
        wall_s=mean("wall_s"),
        errors=sum(1 for r in recs if r.get("error")),
        cap_hits=sum(1 for r in recs if r.get("hit_token_cap")),
    )


def paired(a: dict[int, dict], b: dict[int, dict]) -> Optional[dict]:
    """Compare config a against config b on the problems both finished."""
    idx = sorted(set(a) & set(b))
    if not idx:
        return None
    both = sum(1 for i in idx if a[i]["correct"] and b[i]["correct"])
    a_only = sum(1 for i in idx if a[i]["correct"] and not b[i]["correct"])
    b_only = sum(1 for i in idx if not a[i]["correct"] and b[i]["correct"])
    neither = len(idx) - both - a_only - b_only
    tok_a = sum(a[i].get("generated_tokens", 0) for i in idx)
    tok_b = sum(b[i].get("generated_tokens", 0) for i in idx)
    fp_a = sum(a[i].get("forward_passes", 0) for i in idx)
    fp_b = sum(b[i].get("forward_passes", 0) for i in idx)
    wall_a = sum(a[i].get("wall_s", 0) for i in idx)
    wall_b = sum(b[i].get("wall_s", 0) for i in idx)
    return dict(
        n=len(idx), both=both, a_only=a_only, b_only=b_only, neither=neither,
        acc_diff=(a_only - b_only) / len(idx),
        p=mcnemar_exact(a_only, b_only),
        token_reduction=(1 - tok_a / tok_b) if tok_b else None,
        forward_ratio=(fp_a / fp_b) if fp_b else None,
        wall_reduction=(1 - wall_a / wall_b) if wall_b else None,
    )


def load_results(results_dir: Path, dataset: str, n: Optional[int]) -> dict[str, dict[int, dict]]:
    out = {}
    for cfg in CONFIG_ORDER:
        recs = read_jsonl(results_dir / dataset / f"{cfg}.jsonl")
        if n is not None:
            recs = {i: r for i, r in recs.items() if i < n}
        if recs:
            out[cfg] = recs
    return out


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _p(p: float) -> str:
    return f"{p:.2g}" if p >= 1e-4 else f"{p:.1e}"


def dataset_section(title: str, results: dict[str, dict[int, dict]], expected_n: int,
                    show_p: bool = True) -> list[str]:
    lines = [f"## {title}", ""]
    if not results:
        return lines + ["_No results yet._", ""]
    lines += [
        "| config | correct | accuracy | mean generated tokens | mean forward passes | mean wall s/problem | errors | hit token cap |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for cfg, recs in results.items():
        s = config_stats(list(recs.values()))
        done = "" if s["n"] == expected_n else f" (incomplete: {s['n']}/{expected_n} run)"
        lines.append(
            f"| {cfg}{done} | {s['correct']}/{s['n']} | {_pct(s['correct'] / s['n'])} | "
            f"{s['gen_tokens']:.1f} | {s['forward_passes']:.1f} | {s['wall_s']:.1f} | {s['errors']} | {s['cap_hits']} |"
        )
    lines.append("")
    base = results.get("baseline")
    for cfg in ("latent", "latent-early-exit"):
        if cfg not in results or base is None:
            continue
        c = paired(results[cfg], base)
        if c is None:
            continue
        lines += [
            f"**{cfg} vs baseline** (paired, n = {c['n']}): "
            f"both correct {c['both']}, only {cfg} {c['a_only']}, only baseline {c['b_only']}, neither {c['neither']}. "
            f"Accuracy difference {100 * c['acc_diff']:+.1f} points"
            + (f"; exact two-sided McNemar p = {_p(c['p'])}." if show_p else "."),
            "",
        ]
        if c["token_reduction"] is not None:
            direction = "fewer" if c["token_reduction"] >= 0 else "more"
            lines.append(
                f"- Generated tokens: {cfg} generated {abs(100 * c['token_reduction']):.1f}% {direction} "
                f"tokens than baseline (token reduction {100 * c['token_reduction']:+.1f}%)."
            )
        if c["forward_ratio"] is not None:
            lines.append(
                f"- Forward passes (counts prompt reads, latent steps and decoding): {cfg} used "
                f"{c['forward_ratio']:.2f}x the baseline's."
            )
        if c["wall_reduction"] is not None:
            direction = "less" if c["wall_reduction"] >= 0 else "more"
            lines.append(
                f"- Wall-clock time (measured per problem, same GPU): {cfg} took "
                f"{abs(100 * c['wall_reduction']):.1f}% {direction} time than baseline."
            )
        if c["p"] >= 0.05:
            verdict = (f"no statistically significant accuracy difference between {cfg} and the baseline "
                       f"({100 * c['acc_diff']:+.1f} points, alpha = 0.05)")
        elif c["acc_diff"] > 0:
            verdict = f"{cfg} is more accurate than the baseline, and the difference is statistically significant"
        else:
            verdict = f"{cfg} is **less accurate** than the baseline, and the difference is statistically significant"
        lines += [f"- Verdict: {verdict}.", ""]
    return lines


def build_summary(results_dir: Path, plan: Optional[dict], show_p: bool = True) -> str:
    n = plan.get("n") if plan else None
    lines = ["# Psiduck-AI eval summary", "", "Generated by `analyze.py` from `results/`. Do not edit by hand.", ""]
    if plan:
        s = plan.get("settings", {})
        lines += [
            f"- Model: `{s.get('model_name')}` ({s.get('quantization')}), "
            + (f"sampling at temperature {s.get('temperature')}, top-p {s.get('top_p')}"
               if (s.get("temperature") or 0) > 0 else "greedy decoding")
            + f", seed {s.get('seed')}, thinking {'on' if s.get('thinking', False) else 'off'}, "
            f"max new tokens {s.get('max_new_tokens')}, latent steps/delegate {s.get('latent_steps')}.",
            f"- GSM8K: first N = {n} problems of the test split after a seed-42 shuffle.",
            "- Problems that raised an error count as incorrect.",
            "",
        ]
    lines += dataset_section(f"GSM8K (N = {n})", load_results(results_dir, "gsm8k", n), n or 0, show_p=show_p)
    aime = load_results(results_dir, "aime", None)
    if aime:
        lines += dataset_section("AIME 2024 + 2025 (60 problems)", aime, 60, show_p=show_p)
    amc = load_results(results_dir, "amc23", None)
    if amc:
        lines += dataset_section("Experiment 2: AMC 2023 (40 problems, 4,096-token cap)", amc, 40, show_p=show_p)
    g4k = load_results(results_dir, "gsm8k_4096", 500)
    if g4k:
        lines += dataset_section("Experiment 3: GSM8K at a 4,096-token cap (500 problems)", g4k, 500, show_p=show_p)
    else:
        lines += [
            "## Experiment 3: GSM8K at a 4,096-token cap (in progress)",
            "",
            "Re-runs the same 500 shuffled GSM8K problems with a 4,096-token cap for both configs, to test whether "
            "the GSM8K gap survives when the baseline is not truncated. Results appear here when it finishes.",
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


TLDR_START = "<!-- TLDR:START (generated by analyze.py; do not edit) -->"
TLDR_END = "<!-- TLDR:END -->"
LIMITS_START = "<!-- LIMITATIONS:START (generated by analyze.py; do not edit) -->"
LIMITS_END = "<!-- LIMITATIONS:END -->"


def _headline(results_dir: Path, plan: Optional[dict]) -> Optional[dict]:
    """The main GSM8K numbers shared by the TL;DR and the limitations list."""
    if not plan:
        return None
    res = load_results(results_dir, "gsm8k", plan["n"])
    if "latent" not in res or "baseline" not in res:
        return None
    s = plan["settings"]
    return dict(
        n=plan["n"], cap=s["max_new_tokens"], model=s["model_name"].split("/")[-1], settings=s,
        gpu=(plan.get("environment") or {}).get("gpu"),
        lat=config_stats(list(res["latent"].values())), base=config_stats(list(res["baseline"].values())),
        pair=paired(res["latent"], res["baseline"]),
    )


def build_tldr(results_dir: Path, plan: Optional[dict]) -> str:
    h = _headline(results_dir, plan)
    if h is None:
        return "_Results pending._"
    lat, base, c = h["lat"], h["base"], h["pair"]
    sig = "statistically significant" if c["p"] < 0.05 else "not statistically significant"
    exp1 = (
        f"the latent pipeline scored {100 * lat['correct'] / lat['n']:.1f}% vs {100 * base['correct'] / base['n']:.1f}% "
        f"({sig}), with {100 * c['token_reduction']:.1f}% fewer generated tokens, "
        f"{c['forward_ratio']:.2f}x the forward passes and {100 * c['wall_reduction']:.1f}% less wall-clock time; "
        f"there the baseline ran out of budget on {base['cap_hits']}/{base['n']} problems vs "
        f"{lat['cap_hits']}/{lat['n']} for latent."
    )
    e3 = _exp3(results_dir)
    if e3:
        l3, b3, c3 = e3
        sig3 = "a statistically significant difference" if c3["p"] < 0.05 else "no statistically significant difference"
        lines = [
            f"On {l3['n']} GSM8K problems ({h['model']}) with a 4,096-token cap, the latent pipeline reached "
            f"**{100 * l3['correct'] / l3['n']:.1f}%** vs **{100 * b3['correct'] / b3['n']:.1f}%** for single-model "
            f"chain-of-thought ({sig3}) "
            f"while generating **{100 * c3['token_reduction']:.1f}% fewer tokens**, using "
            f"{c3['forward_ratio']:.2f}x the forward passes and {100 * c3['wall_reduction']:.1f}% less wall-clock time.",
            f"At a {h['cap']:,}-token cap (Experiment 1), {exp1} That accuracy gap disappears once the baseline has "
            "room to finish.",
        ]
    else:
        lines = [
            f"On {h['n']} GSM8K problems ({h['model']}) at a {h['cap']:,}-token cap, {exp1}",
        ]
    others = []
    for name, label in (("aime", "AIME 2024+2025"), ("amc23", "AMC 2023")):
        r = load_results(results_dir, name, None)
        if "latent" in r and "baseline" in r:
            pc = paired(r["latent"], r["baseline"])
            others.append(f"{label} (n = {pc['n']})")
    if others:
        lines.append(f"{' and '.join(others)} showed no statistically significant difference.")
    return "\n".join(lines)


def _exp3(results_dir: Path):
    """(latent stats, baseline stats, paired comparison) for Experiment 3, or None."""
    r = load_results(results_dir, "gsm8k_4096", 500)
    if "latent" not in r or "baseline" not in r or min(len(r["latent"]), len(r["baseline"])) < 500:
        return None
    return (config_stats(list(r["latent"].values())), config_stats(list(r["baseline"].values())),
            paired(r["latent"], r["baseline"]))


def build_limitations(results_dir: Path, plan: Optional[dict]) -> str:
    h = _headline(results_dir, plan)
    if h is None:
        return "_Results pending._"
    lat, base, s = h["lat"], h["base"], h["settings"]
    e3 = _exp3(results_dir)
    truncation = (
        "Experiment 3 shows the gap disappears at a 4,096-token cap (no statistically significant difference, "
        "n = 500)."
        if e3 else "Experiment 3 tests this."
    )
    return "\n".join([
        f"- **One model.** Every result uses {h['model']} ({s['quantization']}); results may not transfer to other "
        "models or sizes.",
        f"- **One sampled run per problem.** Decoding samples at temperature {s['temperature']} with a fixed seed per "
        "problem; run-to-run variance is not measured beyond the paired test.",
        f"- **Baseline truncation.** At the {h['cap']:,}-token cap the baseline hit the cap on "
        f"{base['cap_hits']}/{base['n']} GSM8K problems vs {lat['cap_hits']}/{lat['n']} for latent, so part of the "
        f"accuracy gap could come from finishing within the budget. {truncation}",
        "- **Latent content vs. extra context.** No control replaces or removes the latent states, so it is untested "
        "whether the gain comes from their content or simply from the extra latent positions.",
        "- **AIME and AMC are inconclusive.** On AIME both configs hit the cap on every problem, and AMC has only 40 "
        "problems; neither supports a conclusion.",
        "- **What the compute numbers mean.** Generated tokens count only written text; forward passes also count "
        f"latent steps and prompt reads; wall-clock times come from one {h['gpu'] or 'GPU'} at batch size 1.",
    ])


FIG_COLORS = {"latent": "#2a78d6", "baseline": "#eb6834"}  # categorical slots 1-2, validated for CVD and contrast


def write_figure(results_dir: Path, plan: Optional[dict], path: Path) -> bool:
    """Static SVG: accuracy vs mean forward passes per problem, one small panel per benchmark."""
    n = plan.get("n") if plan else None
    panels = []
    for name, title, limit in (("gsm8k", f"GSM8K, 2,048 cap (n = {n})", n),
                               ("gsm8k_4096", "GSM8K, 4,096 cap (n = 500)", 500),
                               ("amc23", "AMC 2023, 4,096 cap (n = 40)", None),
                               ("aime", "AIME 24+25, 2,048 cap (n = 60)", None)):
        r = load_results(results_dir, name, limit)
        if "latent" in r and "baseline" in r:
            st = {cfg: config_stats(list(r[cfg].values())) for cfg in ("latent", "baseline")}
            panels.append((title, {cfg: (v["forward_passes"], 100 * v["correct"] / v["n"]) for cfg, v in st.items()}))
    if not panels:
        return False
    pw, ph, top, left, gap = 210, 160, 74, 50, 46
    width = left + len(panels) * pw + (len(panels) - 1) * gap + 24
    height = top + ph + 56
    ink, muted, grid, bg = "#2b2b29", "#6b6b66", "#e4e3df", "#fcfcfb"
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" '
        'font-family="Helvetica, Arial, sans-serif">',
        f'<rect width="{width}" height="{height}" fill="{bg}"/>',
        f'<text x="{left}" y="24" font-size="14" font-weight="600" fill="{ink}">'
        "Accuracy vs. compute per problem (higher and further left is better)</text>",
    ]
    lx = left
    for cfg in ("latent", "baseline"):
        out.append(f'<circle cx="{lx + 5}" cy="42" r="5" fill="{FIG_COLORS[cfg]}"/>'
                   f'<text x="{lx + 15}" y="46" font-size="12" fill="{ink}">{cfg}</text>')
        lx += 84
    for k, (title, pts) in enumerate(panels):
        x0 = left + k * (pw + gap)
        xs, ys = [p[0] for p in pts.values()], [p[1] for p in pts.values()]
        xlo, xhi = min(xs) * 0.8, max(xs) * 1.15
        ylo = max(0.0, 10 * (min(ys) // 10) - 10)
        yhi = min(100.0, 10 * (max(ys) // 10) + 10)

        def sx(v, x0=x0, xlo=xlo, xhi=xhi):
            return x0 + (v - xlo) / (xhi - xlo) * pw

        def sy(v, ylo=ylo, yhi=yhi):
            return top + ph - (v - ylo) / (yhi - ylo) * ph

        out.append(f'<text x="{x0}" y="{top - 10}" font-size="12" font-weight="600" fill="{ink}">{title}</text>')
        for t in range(3):
            yv = ylo + t * (yhi - ylo) / 2
            out.append(f'<line x1="{x0}" x2="{x0 + pw}" y1="{sy(yv):.1f}" y2="{sy(yv):.1f}" stroke="{grid}"/>'
                       f'<text x="{x0 - 6}" y="{sy(yv) + 4:.1f}" font-size="10" fill="{muted}" '
                       f'text-anchor="end">{yv:.0f}%</text>')
        for xv in (xlo, (xlo + xhi) / 2, xhi):
            out.append(f'<text x="{sx(xv):.1f}" y="{top + ph + 16}" font-size="10" fill="{muted}" '
                       f'text-anchor="middle">{xv:,.0f}</text>')
        out.append(f'<text x="{x0 + pw / 2}" y="{top + ph + 34}" font-size="10" fill="{muted}" '
                   'text-anchor="middle">mean forward passes per problem</text>')
        (ax, ay), (bx, by) = pts["latent"], pts["baseline"]
        out.append(f'<line x1="{sx(ax):.1f}" y1="{sy(ay):.1f}" x2="{sx(bx):.1f}" y2="{sy(by):.1f}" '
                   f'stroke="{grid}" stroke-width="2"/>')
        for cfg, (xv, yv) in pts.items():
            out.append(f'<circle cx="{sx(xv):.1f}" cy="{sy(yv):.1f}" r="5" fill="{FIG_COLORS[cfg]}" '
                       f'stroke="{bg}" stroke-width="2"/>'
                       f'<text x="{sx(xv):.1f}" y="{sy(yv) - 10:.1f}" font-size="10" fill="{ink}" '
                       f'text-anchor="middle">{yv:.1f}%</text>')
    out.append("</svg>")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    return True


def _replace_block(text: str, start: str, end: str, body: str) -> str:
    if start not in text or end not in text:
        return text
    pre = text.split(start)[0]
    post = text.split(end, 1)[1]
    return f"{pre}{start}\n\n{body}\n\n{end}{post}"


def inject_readme(readme: Path, summary_md: str, tldr: Optional[str] = None,
                  limitations: Optional[str] = None) -> None:
    text = readme.read_text(encoding="utf-8")
    body = summary_md.split("\n", 1)[1].strip()  # drop the "# ..." title line
    body = ("\n" + body).replace("\n## ", "\n### ").strip()
    text = _replace_block(text, README_START, README_END, body)
    if tldr is not None:
        text = _replace_block(text, TLDR_START, TLDR_END, tldr)
    if limitations is not None:
        text = _replace_block(text, LIMITS_START, LIMITS_END, limitations)
    readme.write_text(text, encoding="utf-8")
